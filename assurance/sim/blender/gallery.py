#!/usr/bin/env python3
"""Gallery of the hazard-scene dashboards (assurance/sim/blender).

Copies each scene's dashboard (out/<scene>/dashboard.png from compose.py) to dashboards/<scene>.jpg (1600 px, JPEG
quality 75) and writes dashboards/README.md: one row per catalogue entry with the hazard, its package rating, the
motion, the outcome and the image (a scene without a render keeps its row and says so).

  python3 assurance/sim/blender/gallery.py           # copy and write
  python3 assurance/sim/blender/gallery.py --check   # CI: the README matches the catalogue and the committed images
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
GAL = HERE / "dashboards"
NOTE = "<!-- Generated by assurance/sim/blender/gallery.py from scenes.yaml and out/<scene>/scene.json; do not edit by hand. -->"


def outcome_of(sid: str) -> str:
  f = OUT / sid / "scene.json"
  if f.exists():
    return json.loads(f.read_text(encoding="utf-8"))["outcome"]
  g = GAL / f"{sid}.json"
  return json.loads(g.read_text(encoding="utf-8"))["outcome"] if g.exists() else "not exported"


def render_readme(cat: dict) -> str:
  lines = [NOTE, "", "# Hazard-scene dashboards", "",
           "One dashboard per scene of [`scenes.yaml`](../scenes.yaml), composed by [`compose.py`](../compose.py) from the",
           "posed CAD renders. **Pictures only: synthetic, no evidence credit** ([method](../../README.md#4-what-the-pictures-are-and-are-not)).",
           "The ratings are the package's (WP-C-03 §5), not yet re-rated for OE-1. Every motion is kinematic at an assumed rate;",
           "no actuator, controller, person or contact is modelled.", "",
           "| Scene | Hazard | PLr (package) | Motion | Outcome | Status |", "|---|---|---|---|---|---|"]
  for s in cat["scenes"]:
    sid = s["id"]; m = s["motion"]
    motion = {"joint_sweep": f"{m.get('joint')} {m.get('from', 0):g}° to {m.get('to', 0):g}° at {m.get('rate_dps', 0):g} °/s",
              "gripper_close": f"jaws {m.get('from', 0):g} to {m.get('to', 0):g} mm at {m.get('rate_mms', 0):g} mm/s",
              "drop": "payload free fall", "static": "static pose"}[m["kind"]]
    img = GAL / f"{sid}.jpg"
    status = f"[dashboard]({sid}.jpg)" if img.exists() else "render pending"
    lines.append(f"| `{sid}` | {s['hz']}: {s['title']} | {s['rating']['plr']} (cat. {s['rating']['cat']}) | {motion} (assumed) | {outcome_of(sid)} | {status} |")
  lines.append("")
  for s in cat["scenes"]:
    sid = s["id"]
    if (GAL / f"{sid}.jpg").exists():
      lines += [f"## {sid}", "", f"![Dashboard of {sid}: {s['title']}]({sid}.jpg)", "", f"*{s['caption'].strip()}*", ""]
  return "\n".join(lines)


def main(argv) -> int:
  cat = yaml.safe_load((HERE / "scenes.yaml").read_text(encoding="utf-8"))
  GAL.mkdir(exist_ok=True)
  if "--check" not in argv:
    from PIL import Image
    for s in cat["scenes"]:
      src = OUT / s["id"] / "dashboard.png"
      if src.exists():
        im = Image.open(src).convert("RGB")
        if im.width != 1600:
          im = im.resize((1600, round(im.height * 1600 / im.width)), Image.LANCZOS)
        im.save(GAL / f"{s['id']}.jpg", quality=75, optimize=True)
        sc = json.loads((OUT / s["id"] / "scene.json").read_text(encoding="utf-8"))
        (GAL / f"{s['id']}.json").write_text(json.dumps({"outcome": sc["outcome"], "events": sc["events"], "frames": [{k: f[k] for k in ("i", "t", "label")} for f in sc["frames"]]}, indent=1), encoding="utf-8")
        print(f"copied {s['id']}")
  text = render_readme(cat)
  readme = GAL / "README.md"
  if "--check" in argv:
    if not readme.exists() or readme.read_text(encoding="utf-8") != text:
      print("dashboards/README.md is stale; run gallery.py"); return 1
    for s in cat["scenes"]:
      if s["status"] == "rendered" and not (GAL / f"{s['id']}.jpg").exists():
        print(f"{s['id']}: status rendered but no dashboards/{s['id']}.jpg"); return 1
    print(f"gallery current: {len(cat['scenes'])} scenes, {sum((GAL / (s['id'] + '.jpg')).exists() for s in cat['scenes'])} dashboards")
    return 0
  readme.write_text(text, encoding="utf-8"); print(f"wrote {readme}")
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
